// Regenerates the mini program's data modules from frontend/src (run from anywhere):
//   node miniprogram/tools/build-data.mjs
// - lib/*.json            -> lib/*.js (export default …): the mini program cannot import JSON
// - exercises-data.js     -> data-ex/exercises-data.js, without the media fields img/gif
// - exercise-names/zh.js  -> data-ex/names-zh.js
// - instr/zh.js, instr/en.js, exercise-desc/en.js -> data-instr-zh/, data-instr-en/, data-desc-en/
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const MP = join(dirname(fileURLToPath(import.meta.url)), '..')
const FE = join(MP, '../frontend/src')

for (const name of ['catalogue-v13-ids', 'exercise-muscle-map', 'exercise-muscle-batch-1', 'exercise-muscle-batch-2', 'exercise-muscle-olympic']) {
  const json = JSON.parse(readFileSync(join(FE, 'lib', name + '.json'), 'utf8'))
  writeFileSync(join(MP, 'lib', name + '-data.js'),
    `// generated by miniprogram/tools/build-data.mjs from frontend/src/lib/${name}.json — do not edit\nexport default ${JSON.stringify(json)}\n`)
}

const { EXDB, EXALIAS } = await import(pathToFileURL(join(FE, 'lib/exercises-data.js')).href)
const slim = EXDB.map(({ img, gif, ...rest }) => rest)
mkdirSync(join(MP, 'data-ex'), { recursive: true })
writeFileSync(join(MP, 'data-ex/exercises-data.js'),
  `// generated by miniprogram/tools/build-data.mjs from frontend/src/lib/exercises-data.js (media fields dropped) — do not edit\n` +
  `export const EXDB=${JSON.stringify(slim)}\nexport const EXALIAS=${JSON.stringify(EXALIAS)}\n`)

const copy = (from, to) => { mkdirSync(dirname(join(MP, to)), { recursive: true }); copyFileSync(join(FE, from), join(MP, to)) }
copy('exercise-names/zh.js', 'data-ex/names-zh.js')
copy('instr/zh.js', 'data-instr-zh/instr-zh.js')
copy('instr/en.js', 'data-instr-en/instr-en.js')
copy('exercise-desc/en.js', 'data-desc-en/desc-en.js')

// Every subpackage needs at least one page.
for (const pkg of ['data-ex', 'data-instr-zh', 'data-instr-en', 'data-desc-en']) {
  const d = join(MP, pkg, 'placeholder')
  mkdirSync(d, { recursive: true })
  const files = { 'index.js': 'Page({})\n', 'index.json': '{}\n', 'index.wxml': '<view></view>\n', 'index.wxss': '\n' }
  for (const [f, c] of Object.entries(files)) if (!existsSync(join(d, f))) writeFileSync(join(d, f), c)
}
console.log('ok', slim.length, 'exercises')
