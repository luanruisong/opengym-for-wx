#!/usr/bin/env node
// Rebuilds miniprogram/locales/zh.js from the web app's full pack (frontend/src/locales/zh.js),
// keeping only the keys this build can still ask t()/tn() for. The web pack carries ~2,300 strings,
// half of them for features the mini program does not have (server sync, sign-in, AI coach, admin,
// demo); they cost ~95 KB of the 1.5 MB main package.
//
// A key is kept when it appears as a quoted string literal ('…', "…" or `…`, raw or with the escapes
// a source file would write) anywhere in the mini program's JS or WXML. A key reached only through
// string concatenation would be dropped; the codebase does not build keys that way (t() is always
// called with a literal, or with a value taken from a table of literals, which counts).
// Run after adding UI text: node miniprogram/tools/prune-locale.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = path.join(ROOT, '../frontend/src/locales/zh.js')
const OUT = path.join(ROOT, 'locales/zh.js')

const full = (await import(pathToFileURL(SOURCE).href)).default
// Keys added for the mini program that the web pack does not have: keep them all.
const current = (await import(pathToFileURL(OUT).href + '?t=' + Date.now())).default
const extra = Object.fromEntries(Object.entries(current).filter(([k]) => !(k in full)))

const texts = []
const walk = d => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name)
    if (e.isDirectory()) { if (!['tools', 'locales', 'node_modules'].includes(e.name) && !/^data-/.test(e.name)) walk(p) }
    else if (/\.(js|wxml)$/.test(e.name) && !e.name.endsWith('.test.js')) texts.push(fs.readFileSync(p, 'utf8'))
  }
}
walk(ROOT)
const all = texts.join('\n')
const forms = k => {
  const j = JSON.stringify(k).slice(1, -1)            // \n, \t, \" and \\ escaped
  return [k, j, j.replace(/\\"/g, '"'), k.replace(/'/g, "\\'"), j.replace(/\\"/g, '"').replace(/'/g, "\\'")]
}
const used = k => forms(k).some(f => all.includes("'" + f + "'") || all.includes('"' + f + '"') || all.includes('`' + f + '`'))

const kept = {}
let dropped = 0
for (const [k, v] of Object.entries(full)) { if (used(k)) kept[k] = v; else dropped++ }
Object.assign(kept, extra)

const body = Object.entries(kept).map(([k, v]) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(v) + ',').join('\n')
fs.writeFileSync(OUT,
  '// Simplified Chinese strings for t()/tn(), keyed by the English source text.\n' +
  '// Generated by tools/prune-locale.mjs from frontend/src/locales/zh.js: only the keys this build\n' +
  '// uses. Add a mini-program-only string here by hand; the script keeps keys the web pack lacks.\n' +
  'export default {\n' + body + '\n}\n')
console.log(`zh.js: kept ${Object.keys(kept).length} (${Object.keys(extra).length} mini-program-only), dropped ${dropped}, ` +
  `${(fs.statSync(OUT).size / 1024).toFixed(0)} KB`)
